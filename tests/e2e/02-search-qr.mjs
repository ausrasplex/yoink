import { chromium } from "playwright";
import jsQR from "jsqr"; import { PNG } from "pngjs";
const B = process.env.BASE_URL ?? "http://localhost:3000";
const ok = (c, m) => { console.log(c ? "PASS" : "FAIL", m); if (!c) process.exitCode = 1; };
const br = await chromium.launch();
const ctx = await br.newContext({ viewport: { width: 1280, height: 900 } }); const p = await ctx.newPage();
await p.goto(B + "/login"); await p.getByLabel("Email").fill("alyssa@example.com"); await p.getByLabel("Password").fill("demo-password-1");
await p.getByRole("button", { name: "Sign in" }).click(); await p.waitForURL(B + "/");
await p.goto(B + "/items?q=guitar");
ok(await p.getByRole("link", { name: /Electric guitar/ }).count() === 1 && await p.getByRole("link", { name: /Craft beer/ }).count() === 0, "user search by name");
await p.goto(B + "/items"); await p.getByRole("searchbox", { name: "Search by name or lot number" }).fill("3"); await p.keyboard.press("Enter"); await p.waitForURL(/q=3/);
ok(await p.getByRole("link", { name: /ceramic/ }).count() === 1, "page search box by lot number");
await p.goto(B + "/items?q=zzz"); ok(await p.getByText("Nothing here").isVisible(), "no-results state");
await ctx.close();
const c2 = await br.newContext({ viewport: { width: 1280, height: 1100 } }); const a = await c2.newPage();
await a.goto(B + "/login"); await a.getByLabel("Email").fill("admin@example.com"); await a.getByLabel("Password").fill("change-me-please");
await a.getByRole("button", { name: "Sign in" }).click(); await a.waitForTimeout(1500);
await a.goto(B + "/admin?q=power");
ok(await a.locator("tbody tr").count() === 1, "admin search filters rows");
ok((await a.getByText("Items", { exact: true }).locator("xpath=preceding-sibling::p").first().textContent()) === "8", "admin Items stat unaffected by search");
await a.goto(B + "/admin/qr");
await a.locator("#logo").setInputFiles("fixtures/logo.png"); await a.getByRole("button", { name: "Save" }).click(); await a.waitForTimeout(1200);
await a.goto(B + "/admin/qr");
const svg = a.locator("svg").filter({ has: a.locator("image") }).first();
ok(await svg.count() === 1, "QR renders with logo image");
const png = PNG.sync.read(await svg.screenshot({ path: "shots/qr-logo.png" }));
const res = jsQR(new Uint8ClampedArray(png.data), png.width, png.height);
ok(res?.data === B + "/lot/1", `logo QR still decodes (${res?.data})`);
await a.screenshot({ path: "shots/qr-page.png" });
await a.locator("#qrColor").evaluate((e) => { e.value = "#4c3a9e"; e.dispatchEvent(new Event("input", { bubbles: true })); });
await a.getByLabel("Remove current logo").click(); await a.getByRole("button", { name: "Save" }).click(); await a.waitForTimeout(1200);
await a.goto(B + "/admin/qr");
ok(await a.locator("svg image").count() === 0, "logo removed");
ok(await a.locator('svg path[fill="#4c3a9e"]').count() > 0, "colour applied");
await br.close();
